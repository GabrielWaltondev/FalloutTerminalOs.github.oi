// Fallback to easy if word pool too small
function pickWords(difficulty) {
  const config = WORD_POOLS[difficulty] || WORD_POOLS.average;
  const len = config.length;
  const count = config.count;
  // Filter to actual length match (in case of typos in word list)
  const validWords = config.words.filter(w => w.length === len);
  if (validWords.length < count) {
    console.warn(`Not enough ${len}-letter words in pool. Got ${validWords.length}, need ${count}.`);
  }
  // Shuffle and pick
  const shuffled = [...validWords].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, validWords.length));
}

// ============================================================
// HACK SESSION STATE (one active puzzle)
// ============================================================
const hack = {
  active: false,
  password: null,
  candidates: [],          // current valid candidates (duds get removed)
  attemptsLeft: 4,
  maxAttempts: 4,
  history: [],             // [{guess, score}]
  layout: null,            // generated 2D char array of the screen
  brackets: [],            // {row, startCol, endCol, used}
  wordPositions: [],       // {word, row, startCol, endCol, isDud}
  difficulty: 'average',
  unlockOnWin: null,       // path to unlock when solved (or null)
  onWin: null,             // callback function
  onLose: null,            // callback function
};


// ============================================================
// LAYOUT GENERATION — generates the 32-line screen content
// ============================================================
const JUNK_CHARS = "!@#$%^&*-+=,.;:?/\\|`~";
const BRACKET_PAIRS = [['[',']'], ['{','}'], ['(',')'], ['<','>']];

function generateLayout(words, password) {
  // Two columns of 16 lines, each line has ~12 chars of content + hex address
  const ROWS_PER_COL = 16;
  const CONTENT_PER_LINE = 12;
  const TOTAL_SLOTS = ROWS_PER_COL * 2;

  // Distribute words randomly across the slots
  const wordsToPlace = [...words];
  const slotAssignments = new Array(TOTAL_SLOTS).fill(null);

  // Pick random rows for each word
  const slotIndices = Array.from({length: TOTAL_SLOTS}, (_, i) => i);
  slotIndices.sort(() => Math.random() - 0.5);

  for (let i = 0; i < wordsToPlace.length && i < TOTAL_SLOTS; i++) {
    slotAssignments[slotIndices[i]] = wordsToPlace[i];
  }

  // Build each line's character array
  const layout = [];          // [{leftLine: [...chars], rightLine: [...chars], leftAddr, rightAddr}]
  const wordPositions = [];   // track exact positions of words
  const brackets = [];        // track exact positions of bracket pairs

  // Start with a random base address
  const baseAddr = 0xF000 + Math.floor(Math.random() * 0x0FFF);

  for (let r = 0; r < ROWS_PER_COL; r++) {
    const leftSlot = r;
    const rightSlot = r + ROWS_PER_COL;
    const leftWord = slotAssignments[leftSlot];
    const rightWord = slotAssignments[rightSlot];

    // Build each line
    const leftLine = buildLine(leftWord, CONTENT_PER_LINE, r, 'left', wordPositions);
    const rightLine = buildLine(rightWord, CONTENT_PER_LINE, r, 'right', wordPositions);

    // Find bracket pairs in each line and register them
    findBracketsInLine(leftLine, r, 'left', brackets);
    findBracketsInLine(rightLine, r, 'right', brackets);

    layout.push({
      leftAddr: '0x' + (baseAddr + r * 0x10).toString(16).toUpperCase().padStart(4, '0'),
      rightAddr: '0x' + (baseAddr + (r + ROWS_PER_COL) * 0x10).toString(16).toUpperCase().padStart(4, '0'),
      leftLine,
      rightLine,
    });
  }

  return { layout, wordPositions, brackets };
}

function buildLine(word, length, row, side, wordPositions) {
  // Generate a line with junk; place the word at a random position if there is one
  const chars = [];
  for (let i = 0; i < length; i++) {
    // Sometimes use a bracket char to create potential pairs
    if (Math.random() < 0.20) {
      const pair = BRACKET_PAIRS[Math.floor(Math.random() * BRACKET_PAIRS.length)];
      // Randomly decide open or close
      chars.push(Math.random() < 0.5 ? pair[0] : pair[1]);
    } else {
      chars.push(JUNK_CHARS[Math.floor(Math.random() * JUNK_CHARS.length)]);
    }
  }

  if (word) {
    const startCol = Math.floor(Math.random() * (length - word.length + 1));
    for (let i = 0; i < word.length; i++) {
      chars[startCol + i] = word[i];
    }
    wordPositions.push({
      word,
      row,
      side,
      startCol,
      endCol: startCol + word.length - 1,
      isDud: true,  // will be set to false for password later
    });
  }

  return chars;
}

function findBracketsInLine(lineChars, row, side, brackets) {
  // For each line, find leftmost opening bracket that has a matching closing bracket later
  // Key rule: must NOT have any letters between them (otherwise the word in between is the click target)
  for (let i = 0; i < lineChars.length - 1; i++) {
    const ch = lineChars[i];
    const openIdx = "[{(<".indexOf(ch);
    if (openIdx === -1) continue;

    // Look for the matching closer or any closer of the same family
    const matching = "]})>";
    for (let j = i + 1; j < lineChars.length; j++) {
      // If we hit a letter, this opener doesn't form a bracket pair with anything to its right
      if (/[A-Z]/.test(lineChars[j])) break;
      // Find any closing bracket — game allows mismatched pairs as long as both closes
      if (matching.indexOf(lineChars[j]) !== -1) {
        // Ensure no letters are inside the range
        let hasLetter = false;
        for (let k = i + 1; k < j; k++) {
          if (/[A-Z]/.test(lineChars[k])) { hasLetter = true; break; }
        }
        if (!hasLetter) {
          brackets.push({ row, side, startCol: i, endCol: j, used: false });
          break;  // one bracket per opener
        }
      }
    }
  }
}


// ============================================================
// SCORING — letters in correct position
// ============================================================
function calcLikeness(guess, password) {
  let count = 0;
  for (let i = 0; i < guess.length; i++) {
    if (guess[i] === password[i]) count++;
  }
  return count;
}


