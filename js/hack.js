function renderHackScreen() {
  const screen = document.getElementById("screen-content");
  if (!screen) return;
  screen.innerHTML = "";

  // Header
  const header = document.createElement("div");
  header.className = "hack-header";
  header.innerHTML = `ROBCO INDUSTRIES (TM) TERMLINK PROTOCOL<br>
ENTER PASSWORD NOW<br><br>
<span class="hack-attempts">${hack.attemptsLeft} ATTEMPT(S) LEFT: ${'■ '.repeat(hack.attemptsLeft).trim()}</span><br><br>`;
  screen.appendChild(header);

  // Two-column body
  const body = document.createElement("div");
  body.className = "hack-body";

  for (let r = 0; r < hack.layout.length; r++) {
    const row = hack.layout[r];
    const rowDiv = document.createElement("div");
    rowDiv.className = "hack-row";
    rowDiv.innerHTML = `<span class="hack-addr">${row.leftAddr}</span> <span class="hack-line" data-row="${r}" data-side="left">${renderLine(row.leftLine, r, 'left')}</span> &nbsp;&nbsp; <span class="hack-addr">${row.rightAddr}</span> <span class="hack-line" data-row="${r}" data-side="right">${renderLine(row.rightLine, r, 'right')}</span>`;
    body.appendChild(rowDiv);
  }

  screen.appendChild(body);

  // History panel
  const history = document.createElement("div");
  history.className = "hack-history";
  let historyHTML = '<div class="hack-history-title">&gt; HISTORY</div>';
  if (hack.history.length === 0) {
    historyHTML += '<div class="hack-history-empty">(no attempts yet)</div>';
  } else {
    for (let i = hack.history.length - 1; i >= 0; i--) {
      const h = hack.history[i];
      historyHTML += `<div>&gt; ${h.guess}<br>&gt; ${h.score === 'OK' ? 'Entry granted.' : `${h.score}/${hack.password.length} correct.`}</div>`;
    }
  }
  history.innerHTML = historyHTML;
  screen.appendChild(history);

  // Hint footer
  const hint = document.createElement("div");
  hint.className = "hack-hint";
  hint.innerHTML = `<br>Click a word to guess, or click a [matched] bracket pair for a bonus.<br>Type the word and press Enter to guess. Type 'cancel' or press Esc to abort.`;
  screen.appendChild(hint);

  // Wire up clicks
  attachHackClickHandlers();

  screen.scrollTop = screen.scrollHeight;
}


function renderLine(lineChars, row, side) {
  // Convert a line of chars into HTML with clickable word/bracket spans
  let html = '';
  let i = 0;

  // Build word positions and bracket positions for this specific row+side
  const wordsHere = hack.wordPositions.filter(w => w.row === row && w.side === side);
  const bracketsHere = hack.brackets.filter(b => b.row === row && b.side === side);

  while (i < lineChars.length) {
    // Check if we're at the start of a word
    const wordHere = wordsHere.find(w => w.startCol === i);
    if (wordHere && hack.candidates.includes(wordHere.word)) {
      const word = wordHere.word;
      // Each letter gets its own span for individual hover highlight
      // Parent span gets word-level hover treatment via JS mouseenter/leave
      const letterSpans = word.split("").map(ch =>
        `<span class="hack-letter">${escapeHtml(ch)}</span>`
      ).join("");
      html += `<span class="hack-word" data-word="${word}">${letterSpans}</span>`;
      i += word.length;
      continue;
    }
    // Check if we're at the start of a bracket pair (not used)
    const bracketHere = bracketsHere.find(b => b.startCol === i && !b.used);
    if (bracketHere) {
      const segment = lineChars.slice(bracketHere.startCol, bracketHere.endCol + 1).join('');
      // Each char in the bracket pair gets its own span too
      const charSpans = segment.split("").map(ch =>
        `<span class="hack-bracket-char">${escapeHtml(ch)}</span>`
      ).join("");
      html += `<span class="hack-bracket" data-row="${row}" data-side="${side}" data-start="${bracketHere.startCol}">${charSpans}</span>`;
      i = bracketHere.endCol + 1;
      continue;
    }
    // Default: render single char (could be a removed dud's blanked space or junk)
    const wordOverlap = wordsHere.find(w => i >= w.startCol && i <= w.endCol);
    if (wordOverlap && !hack.candidates.includes(wordOverlap.word)) {
      // Dud has been removed — replace word's letters with a dot
      html += '.';
      i++;
      continue;
    }
    html += escapeHtml(lineChars[i]);
    i++;
  }

  return html;
}


function escapeHtml(s) {
  return String(s).replace(/[<>&"']/g, c => ({'<':'&lt;','>':'&gt;','&':'&amp;','"':'&quot;',"'":'&#39;'}[c]));
}


function attachHackClickHandlers() {
  // Words
  document.querySelectorAll('.hack-word').forEach(el => {
    el.addEventListener('click', () => {
      const word = el.dataset.word;
      if (word) submitGuess(word);
    });
    el.addEventListener('mouseenter', () => el.classList.add('hover'));
    el.addEventListener('mouseleave', () => el.classList.remove('hover'));
  });
  // Brackets
  document.querySelectorAll('.hack-bracket').forEach(el => {
    el.addEventListener('click', () => {
      const row = parseInt(el.dataset.row);
      const side = el.dataset.side;
      const start = parseInt(el.dataset.start);
      activateBracket(row, side, start);
    });
    el.addEventListener('mouseenter', () => el.classList.add('hover'));
    el.addEventListener('mouseleave', () => el.classList.remove('hover'));
  });
}


// ============================================================
// GUESSING / BRACKETS / WIN / LOSE
// ============================================================
function submitGuess(word) {
  if (!hack.active) return;
  word = word.toUpperCase();
  if (!hack.candidates.includes(word)) {
    // Show feedback that it's not a valid choice
    flashScreenMessage(`> ${word}\n> Not a valid candidate.`);
    return;
  }

  const score = calcLikeness(word, hack.password);

  if (word === hack.password) {
    hack.history.push({ guess: word, score: 'OK' });
    renderHackScreen();
    setTimeout(() => winHack(), 800);
    return;
  }

  hack.history.push({ guess: word, score });
  hack.attemptsLeft--;

  // Remove the wrong word from candidates
  hack.candidates = hack.candidates.filter(c => c !== word);

  if (hack.attemptsLeft <= 0) {
    renderHackScreen();
    setTimeout(() => loseHack(), 800);
    return;
  }

  renderHackScreen();
}


function activateBracket(row, side, start) {
  if (!hack.active) return;
  const b = hack.brackets.find(x => x.row === row && x.side === side && x.startCol === start);
  if (!b || b.used) return;

  // Game rule: if only one candidate left, "Entry Denied" (no effect)
  if (hack.candidates.length <= 1) {
    flashScreenMessage('> Entry Denied.');
    return;
  }

  b.used = true;

  // 50/50: dud removal or attempts replenish (game-canonical behavior)
  // Slightly weighted toward dud removal since that's more common in the game
  const replenish = Math.random() < 0.30;

  if (replenish) {
    hack.attemptsLeft = hack.maxAttempts;
    flashScreenMessage('> Allowance Replenished.');
  } else {
    // Pick a random non-password candidate to remove
    const duds = hack.candidates.filter(c => c !== hack.password);
    if (duds.length > 0) {
      const removed = duds[Math.floor(Math.random() * duds.length)];
      hack.candidates = hack.candidates.filter(c => c !== removed);
      flashScreenMessage(`> Dud Removed.`);
    } else {
      flashScreenMessage('> Entry Denied.');
    }
  }
  setTimeout(() => renderHackScreen(), 500);
}


function flashScreenMessage(msg) {
  const screen = document.getElementById("screen-content");
  if (!screen) return;
  const div = document.createElement("div");
  div.className = "hack-flash";
  div.textContent = msg;
  screen.appendChild(div);
  screen.scrollTop = screen.scrollHeight;
  setTimeout(() => { if (div.parentElement) div.remove(); }, 2000);
}


function winHack() {
  hack.active = false;
  const screen = document.getElementById("screen-content");
  screen.innerHTML = '';
  const div = document.createElement("div");
  div.className = "line line-bright";
  div.innerHTML = `<br><br>> EXACT MATCH!<br>> PLEASE WAIT WHILE SYSTEM IS ACCESSED.<br><br>> ACCESS GRANTED.<br>`;
  screen.appendChild(div);

  // Optional unlock
  if (hack.unlockOnWin && window.UNLOCKED_FILES) {
    window.UNLOCKED_FILES.add(hack.unlockOnWin);
    const unlockDiv = document.createElement("div");
    unlockDiv.className = "line line-bright";
    unlockDiv.innerHTML = `<br>> File unlocked: ${hack.unlockOnWin}<br>> Use 'read ${hack.unlockOnWin}' to view contents.<br>`;
    screen.appendChild(unlockDiv);
  }

  setTimeout(() => {
    if (window.terminal) window.terminal.showPrompt();
    if (hack.onWin) hack.onWin();
  }, 1800);
}


function loseHack() {
  hack.active = false;
  const screen = document.getElementById("screen-content");
  screen.innerHTML = '';
  const div = document.createElement("div");
  div.className = "line line-error";
  div.innerHTML = `<br><br>> TERMINAL LOCKED OUT<br>> PLEASE CONTACT AN ADMINISTRATOR.<br><br>> The password was: ${hack.password}<br>`;
  screen.appendChild(div);
  setTimeout(() => {
    if (window.terminal) window.terminal.showPrompt();
    if (hack.onLose) hack.onLose();
  }, 2000);
}


// ============================================================
// PUBLIC API — start a hack
// ============================================================
function startHack(options = {}) {
  const difficulty = options.difficulty || 'average';
  const config = WORD_POOLS[difficulty];
  if (!config) {
    return { error: `Unknown difficulty: ${difficulty}. Try: very_easy, easy, average, hard.` };
  }

  const words = pickWords(difficulty);
  if (words.length === 0) {
    return { error: "Couldn't generate puzzle words." };
  }

  const password = words[Math.floor(Math.random() * words.length)];
  const { layout, wordPositions, brackets } = generateLayout(words, password);

  // Mark the password word
  for (const wp of wordPositions) {
    if (wp.word === password) wp.isDud = false;
  }

  hack.active = true;
  hack.password = password;
  hack.candidates = [...words];
  hack.attemptsLeft = 4;
  hack.maxAttempts = 4;
  hack.history = [];
  hack.layout = layout;
  hack.wordPositions = wordPositions;
  hack.brackets = brackets;
  hack.difficulty = difficulty;
  hack.unlockOnWin = options.unlockOnWin || null;
  hack.onWin = options.onWin || null;
  hack.onLose = options.onLose || null;

  // Keep the prompt visible during the puzzle so the user can type guesses
  // (the prompt-path will show the difficulty for context)
  const pathEl = document.getElementById("prompt-path");
  if (pathEl) pathEl.textContent = `[hack:${difficulty}]`;

  renderHackScreen();
  return { ok: true };
}


function cancelHack() {
  if (!hack.active) return;
  hack.active = false;
  if (window.terminal) window.terminal.showPrompt();
}


